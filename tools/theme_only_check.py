"""Fail when frontend code sets a visual value outside the theme layer, or imports UI from outside HeroUI (DESIGN.md).

DESIGN.md, Theming and Stack: HeroUI v3 components are used as they are, every visual value is a variable in
`frontend/src/app/theme.css`, and `@heroui/react` is the single UI layer. So a visual change is an edit to theme.css
only. Scans the tracked files under `frontend/src/`, except theme.css itself, test files and generated files, and
reports:
- a CSS file other than theme.css (the entry CSS, which imports tailwindcss and @heroui/styles);
- in source files: a color literal, a Tailwind arbitrary value, a Tailwind palette color utility, a `style=` prop,
  or an import of a package other than `@heroui/react`, its icon set and the non-UI runtime packages.
Prints `path:line: rule: text` per finding and exits 1, or prints one summary line and exits 0.

Checks the repository this file is in; it takes no arguments.
"""

import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SCOPE = "frontend/src/"
THEME = "frontend/src/app/theme.css"
SOURCE_SUFFIXES = (".ts", ".tsx", ".js", ".jsx", ".mts", ".cts")
# Tests and their setup render components but ship nothing; the API types are generated by `make api-client`.
EXEMPT = re.compile(r"\.test\.[cm]?[jt]sx?$|^frontend/src/test/|^frontend/src/api/schema\.d\.ts$")

# Tailwind CSS v4's named color palettes (tailwindcss/theme.css, `--color-<palette>-<shade>`), plus black and white.
PALETTES = (
    "slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet"
    "|purple|fuchsia|pink|rose"
)

# The packages app code may import. `@heroui/react` is the only UI package, with one icon set beside it; the rest are
# not UI. A new runtime dependency is added here in the PR that adds it to package.json.
RUNTIME_PACKAGES = (
    r"@heroui/react|@gravity-ui/icons|react|react-dom|react-router|openapi-fetch|@tanstack/react-query"
    r"|@internationalized/date"
)

# Each rule's structural property: visual values live only in the theme layer, and @heroui/react is the single UI
# layer (DESIGN.md, Theming and Stack).
RULES: tuple[tuple[str, re.Pattern[str]], ...] = (
    # CSS Color 4 hex notation (#rgb, #rgba, #rrggbb, #rrggbbaa) and its color functions.
    ("color literal", re.compile(r"(?<![\w&])#(?:[0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})\b")),
    ("color literal", re.compile(r"\b(?:rgba?|hsla?|oklch)\(")),
    # Tailwind arbitrary values, `utility-[value]`: a value written in the class instead of the theme.
    ("arbitrary value", re.compile(r"(?<![\w-])[a-z][\w:/.-]*-\[[^\]\s]*\]")),
    # Tailwind palette colors chosen per component instead of HeroUI's semantic tokens.
    (
        "palette color",
        re.compile(rf"(?<![\w-])(?:bg|text|border|ring|fill|stroke)-(?:(?:{PALETTES})-\d{{2,3}}|black|white)\b"),
    ),
    # An inline style in JSX: a visual value set on one element.
    ("style prop", re.compile(r"(?<![\w-])style=\{")),
    # A package outside RUNTIME_PACKAGES: React Aria directly (HeroUI already wraps it with its styles), or a second
    # UI layer next to HeroUI.
    (
        "ui import",
        re.compile(rf"""(?:\bfrom\s+|^\s*import\s+|\bimport\s*\(\s*)["'](?![./])(?!(?:{RUNTIME_PACKAGES})["'/])"""),
    ),
)


def tracked_files(root: Path) -> list[str]:
    # Git writes paths as UTF-8 bytes; decoding them with the locale's encoding would misread non-ASCII names.
    output = subprocess.run(  # noqa: S603
        ["git", "-C", str(root), "ls-files", "-z", "--", SCOPE],  # noqa: S607
        capture_output=True,
        check=True,
    ).stdout.decode("utf-8")
    return [path for path in output.split("\0") if path and path != THEME and not EXEMPT.search(path)]


def line_findings(path: str, text: str) -> list[str]:
    return [
        f"{path}:{number}: {name}: {line.strip()}"
        for number, line in enumerate(text.splitlines(), start=1)
        for name, pattern in RULES
        if pattern.search(line)
    ]


def findings(root: Path, paths: list[str]) -> list[str]:
    found: list[str] = []
    for path in paths:
        if path.endswith(".css"):
            found.append(f"{path}:1: css file: visual values go in {THEME}")
        elif path.endswith(SOURCE_SUFFIXES):
            found.extend(line_findings(path, (root / path).read_text(encoding="utf-8")))
    return found


def main() -> int:
    paths = tracked_files(REPO)
    found = findings(REPO, paths)
    for finding in found:
        print(finding)
    if found:
        print(
            f"theme-only: {len(found)} findings. Visual values belong in {THEME} and UI comes from @heroui/react "
            "(openspec/conventions/DESIGN.md, Theming and Stack).",
            file=sys.stderr,
        )
        return 1
    print(f"theme-only: ok, {len(paths)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
