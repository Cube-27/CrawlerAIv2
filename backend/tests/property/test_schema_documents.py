"""Schema documents (SPEC-04 §6, SPEC-13 §6): generated valid documents, with path alternatives and row-mapped
fields, round-trip through the model and its JSON, and through role S's wire form (SPEC-06 §4.5); a `schema_org` path
that breaks the schema.org naming conventions is rejected wherever it appears, and so is a row mapping that breaks the
SPEC-13 §4.2 rules."""

import string
from typing import Any, get_args

import pytest
from hypothesis import given
from hypothesis import strategies as st
from jsonschema import Draft202012Validator
from pydantic import ValidationError

from crawlerai.llm.roles.s_wire import from_wire, to_wire, wire_schema
from crawlerai.schemas.types import FieldType, IdentifierScheme, SchemaDocument

_names = st.from_regex(r"[a-z][a-z0-9_]{0,10}", fullmatch=True)
_tail = st.text(alphabet=string.ascii_letters + string.digits, max_size=8)
_type_name = st.builds(str.__add__, st.sampled_from(string.ascii_uppercase), _tail)
_property = st.builds(str.__add__, st.sampled_from(string.ascii_lowercase), _tail)
_steps = st.builds(lambda t, props: f"{t}.{'.'.join(props)}", _type_name, st.lists(_property, min_size=1, max_size=3))
_alternative = st.builds(lambda path, joined: path + (f"+{joined}" if joined else ""), _steps, st.none() | _property)
_schema_org = st.lists(_alternative, min_size=1, max_size=4).map("|".join)
# A row path names nodes, so it joins no value (SPEC-13 §4.2).
_row_path = st.lists(_steps, min_size=1, max_size=4).map("|".join)
_description = st.text(max_size=20).map(str.strip).filter(bool)
_SCALARS = [t for t in FieldType if t not in (FieldType.LIST, FieldType.OBJECT)]


def _parameters(type_: FieldType) -> st.SearchStrategy[dict[str, Any]]:
    if type_ is FieldType.ENUM:
        return st.builds(
            lambda v: {"vocab": v}, st.from_regex(r"(schema:[A-Z][a-z]{1,6}|type:[a-z]{1,6})", fullmatch=True)
        )
    if type_ is FieldType.IDENTIFIER:
        return st.builds(lambda s: {"scheme": s}, st.sampled_from(get_args(IdentifierScheme)))
    return st.just({})


def _spec(depth: int, *, described: bool) -> st.SearchStrategy[dict[str, Any]]:
    types = list(FieldType) if depth < 3 else _SCALARS
    return st.sampled_from(types).flatmap(lambda t: _spec_of(t, depth, described=described))


def _spec_of(type_: FieldType, depth: int, *, described: bool) -> st.SearchStrategy[dict[str, Any]]:
    # A list's path is drawn with its item: a list of objects with a path is row-mapped, generated by `_row_mapped`.
    optional = {"required": st.booleans()} | ({} if type_ is FieldType.LIST else {"schema_org": _schema_org})
    common = st.fixed_dictionaries({"type": st.just(type_.value)}, optional=optional)
    parts = [common, _parameters(type_)]
    if described:
        parts.append(st.builds(lambda d: {"description": d}, _description))
    if type_ is FieldType.LIST:
        parts.append(_spec(depth + 1, described=False).flatmap(_list_item))
    if type_ is FieldType.OBJECT:
        parts.append(
            st.builds(
                lambda f: {"fields": f},
                st.dictionaries(_names, _spec(depth + 1, described=True), min_size=1, max_size=3),
            )
        )
    return st.tuples(*parts).map(lambda ds: {k: v for d in ds for k, v in d.items()})


def _list_item(item: dict[str, Any]) -> st.SearchStrategy[dict[str, Any]]:
    if item["type"] == FieldType.OBJECT.value:
        return st.just({"item": item})
    return st.fixed_dictionaries({"item": st.just(item)}, optional={"schema_org": _schema_org})


def _row_mapped() -> st.SearchStrategy[dict[str, Any]]:
    """A row-mapped field (SPEC-13 §4.2): a top-level list of objects with a row path, whose `key` names one to three
    identifier or url sub-fields."""
    key_spec = st.sampled_from([FieldType.IDENTIFIER, FieldType.URL]).flatmap(lambda t: _spec_of(t, 3, described=True))
    keys = st.dictionaries(_names, key_spec, min_size=1, max_size=3)
    others = st.dictionaries(_names, _spec(3, described=True), max_size=2)
    return st.builds(
        lambda key_fields, other_fields, path, description: {
            "type": "list",
            "description": description,
            "schema_org": path,
            "key": list(key_fields),
            "item": {"type": "object", "fields": other_fields | key_fields},
        },
        keys,
        others,
        _row_path,
        _description,
    )


_documents = st.fixed_dictionaries(
    {
        "name": _names,
        "version": st.integers(min_value=1, max_value=10_000),
        "page_kind": st.just("detail"),
        "fields": st.dictionaries(_names, _spec(1, described=True) | _row_mapped(), min_size=1, max_size=4),
    }
)


@given(_documents)
def test_valid_documents_round_trip_through_json_and_the_role_s_wire_form(raw: dict[str, Any]) -> None:
    document = SchemaDocument.model_validate(raw)

    assert SchemaDocument.model_validate_json(document.model_dump_json(exclude_none=True)) == document
    assert document.model_dump(mode="json", exclude_none=True, exclude_defaults=True) == {
        **raw,
        "fields": _without_defaults(raw["fields"]),
    }
    wire = to_wire(document.model_dump(mode="json", exclude={"name", "version"}, exclude_none=True))

    assert list(Draft202012Validator(wire_schema()).iter_errors(wire)) == []
    assert (
        SchemaDocument.model_validate({**from_wire(wire), "name": raw["name"], "version": raw["version"]}) == document
    )


def _without_defaults(fields: dict[str, Any]) -> dict[str, Any]:
    return {name: _spec_without_defaults(spec) for name, spec in fields.items()}


def _spec_without_defaults(spec: dict[str, Any]) -> dict[str, Any]:
    out = {k: v for k, v in spec.items() if not (k == "required" and v is False)}
    if "item" in out:
        out["item"] = _spec_without_defaults(out["item"])
    if "fields" in out:
        out["fields"] = _without_defaults(out["fields"])
    return out


_bad_paths = (
    _property  # no type
    | st.builds(lambda p: f"{p}.name", _property)  # lowercase type
    | st.builds(lambda t: f"{t}.Name", _type_name)  # uppercase property
    | st.builds(lambda path: f"{path}+", _row_path)  # empty joined property
    | st.builds(lambda path, p: f"{path}+{p}+{p}", _row_path, _property)
    | st.builds(lambda path: f"{path}|", _schema_org)  # empty alternative
    | st.lists(_alternative, min_size=5, max_size=6).map("|".join)  # more than four alternatives
)


@given(_documents, _bad_paths)
def test_a_malformed_schema_org_path_is_rejected(raw: dict[str, Any], path: str) -> None:
    name = next(iter(raw["fields"]))
    raw["fields"][name] = {**raw["fields"][name], "schema_org": path}

    with pytest.raises(ValidationError) as error:
        SchemaDocument.model_validate(raw)

    assert any(e["loc"][-1] == "schema_org" for e in error.value.errors())


def _row_breakers() -> st.SearchStrategy[tuple[str, Any]]:
    """A change to a row-mapped field that breaks a SPEC-13 §4.2 rule, as (what it changes, the new value)."""
    return st.one_of(
        st.builds(lambda path, p: ("schema_org", f"{path}+{p}"), _row_path, _property),  # a row path joins no value
        st.just(("key", None)),  # a row-mapped field needs a key
        st.just(("key", [])),
        st.builds(lambda names: ("key", names), st.lists(_names, min_size=4, max_size=5, unique=True)),
        st.just(("text_key", None)),  # a key sub-field is an identifier or url
        st.just(("nested", None)),  # sub-fields are leaf values
        st.builds(lambda path: ("item_path", path), _schema_org),  # the list's path names the rows
    )


def _broken(field: dict[str, Any], change: str, value: Any) -> dict[str, Any]:
    item = dict(field["item"])
    sub = {"type": "text", "description": "d"}
    if change == "text_key":
        return {**field, "key": ["k_text"], "item": {**item, "fields": {**item["fields"], "k_text": sub}}}
    if change == "nested":
        nested = {"type": "list", "description": "d", "item": {"type": "text"}}
        return {**field, "item": {**item, "fields": {**item["fields"], "k_nested": nested}}}
    if change == "item_path":
        return {**field, "item": {**item, "schema_org": value}}
    return {**field, change: value} if value is not None else {k: v for k, v in field.items() if k != change}


def _document(**fields: dict[str, Any]) -> dict[str, Any]:
    """A valid document with one plain field and `fields`."""
    return {
        "name": "doc",
        "version": 1,
        "page_kind": "detail",
        "fields": {"title": {"type": "text", "description": "d"}, **fields},
    }


@given(_row_mapped(), _row_breakers())
def test_a_row_mapping_that_breaks_its_rules_is_rejected(field: dict[str, Any], breaker: tuple[str, Any]) -> None:
    SchemaDocument.model_validate(_document(k_row=field))  # valid before the change
    raw = _document(k_row=_broken(field, *breaker))

    with pytest.raises(ValidationError):
        SchemaDocument.model_validate(raw)


@given(st.sampled_from(list(FieldType)).flatmap(lambda t: _spec_of(t, 1, described=True)))
def test_a_key_outside_a_row_mapped_field_is_rejected(spec: dict[str, Any]) -> None:
    raw = _document(k_field={k: v for k, v in spec.items() if k != "schema_org"} | {"key": ["a"]})

    with pytest.raises(ValidationError, match="`key` is only for"):
        SchemaDocument.model_validate(raw)
